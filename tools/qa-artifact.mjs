// Loads the packed single-file build inside a strictly sandboxed iframe (opaque origin: storage throws,
// no downloads, no popups) and drives it the way a viewer would.
// Usage: node tools/qa-artifact.mjs [http://localhost:8099/preview.html] [WxH]
import { chromium } from 'playwright';
const url = process.argv[2] || 'http://localhost:8099/preview.html';
const [W, H] = (process.argv[3] || '1440x900').split('x').map(Number);
const sandbox = process.env.SANDBOX ?? 'allow-scripts';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: W, height: H } });
const errors = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errors.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`[pageerror] ${e.message}`));
page.on('requestfailed', (r) => errors.push(`[requestfailed] ${r.url().slice(0, 100)}`));
const external = [];
page.on('request', (r) => { const u = r.url(); if (!u.startsWith('data:') && !u.startsWith(new URL(url).origin) && !u.startsWith('blob:') && u !== 'about:blank') external.push(u); });
await page.setContent(`<!doctype html><body style="margin:0;background:#222"><iframe id="f" sandbox="${sandbox}" src="${url}" style="border:0;width:100vw;height:100vh"></iframe></body>`);
const fh = await page.waitForSelector('#f');
const frame = await fh.contentFrame();
await frame.waitForFunction(() => document.getElementById('app') && document.getElementById('app').dataset.ready === '1', null, { timeout: 30000 });
const out = {};
out.title = await frame.title();
out.storageThrows = await frame.evaluate(() => { try { localStorage.getItem('x'); return false; } catch { return true; } });
out.fullscreenEnabled = await frame.evaluate(() => document.fullscreenEnabled);
out.fullBtnHidden = await frame.evaluate(() => getComputedStyle(document.getElementById('btnFull')).display === 'none');
await page.screenshot({ path: `${process.env.OUT || '/tmp/claude-0/shots'}/art_title_${W}x${H}.png` });
await frame.click('#btnBegin');
await frame.waitForFunction(() => __player.state === 'playing', null, { timeout: 40000 });
await page.waitForTimeout(2500);
out.playing = await frame.evaluate(() => ({ idx: __player.idx, t: +__player.master.time().toFixed(1) }));
out.audio = await frame.evaluate(async () => { const m = await import('data:text/javascript,0').catch(() => 0); return null; }).catch(() => null);
await page.keyboard.press('Space'); await page.waitForTimeout(300);
out.pausedByKey = await frame.evaluate(() => __player.state);
await page.keyboard.press('Space'); await page.waitForTimeout(300);
out.resumedByKey = await frame.evaluate(() => __player.state);
await page.keyboard.press('m'); out.soundToggle = await frame.evaluate(() => document.getElementById('btnSound').getAttribute('aria-pressed'));
await page.keyboard.press('m');
await frame.click('#btnMenuTop'); await page.waitForTimeout(800);
out.thumbs = await frame.evaluate(() => [...document.querySelectorAll('.mcard-img img')].map((i) => i.complete && i.naturalWidth > 0));
await page.screenshot({ path: `${process.env.OUT || '/tmp/claude-0/shots'}/art_menu_${W}x${H}.png` });
await frame.click('.mcard[data-i="4"]');
await frame.waitForFunction(() => __player.state === 'playing' && __player.idx === 4, null, { timeout: 40000 });
await page.waitForTimeout(1500);
out.jumped = await frame.evaluate(() => ({ idx: __player.idx, t: +__player.master.time().toFixed(1) }));
await page.screenshot({ path: `${process.env.OUT || '/tmp/claude-0/shots'}/art_ch5_${W}x${H}.png` });
out.layout = await frame.evaluate(() => document.getElementById('app').dataset.layout);
out.horizontalScroll = await frame.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
out.external = external;
out.errors = errors;
console.log(JSON.stringify(out, null, 2));
await browser.close();
